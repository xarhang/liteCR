/** Resolve a message from one already-published namespace bundle. */
export function createUiTranslator(entries: Record<string, string> | null | undefined) {
  return (key: string, sourceFallback?: string, values?: Record<string, string | number>): string => {
    const published = entries?.[key];
    const template = typeof published === 'string' && published.trim()
      ? published
      : sourceFallback ?? englishUiMessages[key] ?? humanizeKey(key);
    return template.replace(/\{\{([a-zA-Z][a-zA-Z0-9_]*)\}\}/g, (match, name: string) => {
      const value = values?.[name];
      return value === undefined ? match : String(value);
    });
  };
}

/** Compatibility helper for code that needs a source fallback before bundle load. */
export function translateProvisional(_locale: string, key: string): string {
  return createUiTranslator(undefined)(key);
}

function humanizeKey(key: string): string {
  const words = key.replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[._\s-]+/).filter(Boolean);
  if (!words.length) return 'Label unavailable';
  return words.map((word, index) => index === 0 ? word[0].toUpperCase() + word.slice(1).toLowerCase() : word.toLowerCase()).join(' ');
}
